import { test, expect } from "@playwright/test";

test("logical lighting channels share GND, persist in templates and appear once per report", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem("easyschematic-skip-landing", "1"));
  await page.goto("/");
  await expect(page.locator(".react-flow")).toBeVisible({ timeout: 30000 });
  const fixture = { version: 47, name: "Pixel Channels", nodes: [{ id: "pixel", type: "device", position: { x: 0, y: 0 }, data: { label: "Pixel Controller", deviceType: "generic", ports: [
    ...["B1", "A1/D1", "C1", "B2", "A2/D2", "C2", "GND"].map((label, i) => ({ id: `p${i}`, label, direction: "output", signalType: "spi", connectorType: "terminal-block" })),
    { id: "lan", label: "LAN", direction: "bidirectional", signalType: "artnet", connectorType: "rj45", networkConfig: { ip: "2.0.0.10" } },
  ] } }], edges: [] };
  await page.locator('input[type=file][accept=".json"]').first().setInputFiles({ name: "pixels.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(fixture)) });
  await page.locator('.react-flow__node[data-id="pixel"]').dblclick();
  const section = page.getByTestId("virtual-channels");
  await section.getByRole("button", { name: "+ Add Virtual Channel", exact: true }).click();
  const first = page.getByTestId("virtual-channel").nth(0);
  await first.getByLabel("Virtual channel protocol", { exact: true }).selectOption("artnet");
  await first.getByLabel("Virtual channel output signal", { exact: true }).selectOption("spi");
  for (const port of ["B1", "A1/D1", "C1", "GND"]) await first.getByLabel(port, { exact: true }).check();
  await first.getByLabel("Channel start universe", { exact: true }).fill("0");
  await first.getByLabel("Channel DMX start address", { exact: true }).fill("1");
  await first.getByLabel("Channel pixel count", { exact: true }).fill("171");
  await first.getByLabel("Universe packing", { exact: true }).selectOption("whole-pixels");
  await expect(first).toContainText("→ U1:3 · 513 ch");
  await first.screenshot({ path: test.info().outputPath("virtual-channel-editor.png") });
  await section.getByRole("button", { name: "+ Add Virtual Channel", exact: true }).click();
  const second = page.getByTestId("virtual-channel").nth(1);
  await second.getByLabel("Virtual channel protocol", { exact: true }).selectOption("artnet");
  for (const port of ["B2", "A2/D2", "C2", "GND"]) await second.getByLabel(port, { exact: true }).check();
  await second.getByLabel("Channel start universe", { exact: true }).fill("2");
  await second.getByLabel("Channel DMX start address", { exact: true }).fill("101");
  await second.getByLabel("Channel manual footprint", { exact: true }).fill("48");
  await expect(section.getByRole("alert")).toHaveCount(0);
  await page.getByRole("button", { name: "Save as User Template", exact: true }).click();
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await page.reload();
  await page.locator('.react-flow__node[data-id="pixel"]').dblclick();
  await expect(page.getByTestId("virtual-channel")).toHaveCount(2);
  await expect(first.getByLabel("GND", { exact: true })).toBeChecked();
  await expect(second.getByLabel("GND", { exact: true })).toBeChecked();
  await expect(first.getByLabel("Channel pixel count", { exact: true })).toHaveValue("171");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await page.evaluate(() => window.dispatchEvent(new CustomEvent("easyschematic:open-reports", { detail: "lighting" })));
  await expect(page.getByRole("cell", { name: "Channel 1 [B1, A1/D1, C1, GND]", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "Channel 2 [B2, A2/D2, C2, GND]", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "U1:3", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "2.0.0.10", exact: true })).toHaveCount(2);
  expect(errors).toEqual([]);
});

test("virtual-channel configuration follows its protocol and separate output signal", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("easyschematic-skip-landing", "1"));
  await page.goto("/");
  await expect(page.locator(".react-flow")).toBeVisible({ timeout: 30000 });
  const fixture = { version: 48, nodes: [{ id: "device", type: "device", position: { x: 0, y: 0 }, data: { label: "Generic Controller", deviceType: "generic", ports: [{ id: "p", label: "Terminal", direction: "output", signalType: "custom" }] } }], edges: [] };
  await page.locator('input[type=file][accept=".json"]').first().setInputFiles({ name: "virtual.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(fixture)) });
  await page.locator('.react-flow__node[data-id="device"]').dblclick();
  await page.getByRole("button", { name: "+ Add Virtual Channel", exact: true }).click();
  const channel = page.getByTestId("virtual-channel");
  await channel.getByLabel("Terminal", { exact: true }).check();
  await channel.getByLabel("Virtual channel protocol", { exact: true }).selectOption("ethernet");
  await expect(channel.getByLabel("Channel start universe", { exact: true })).toHaveCount(0);
  await expect(channel.getByLabel("Channel pixel count", { exact: true })).toHaveCount(0);
  await channel.getByRole("button", { name: "+ Add protocol parameter", exact: true }).click();
  await channel.getByLabel("Protocol parameter name", { exact: true }).fill("VLAN");
  await channel.getByLabel("Protocol parameter value", { exact: true }).fill("20");
  await channel.getByLabel("Virtual channel protocol", { exact: true }).selectOption("artnet");
  await expect(channel.getByLabel("Channel start universe", { exact: true })).toBeVisible();
  await expect(channel.getByLabel("Channel pixel count", { exact: true })).toHaveCount(0);
  await channel.getByLabel("Virtual channel output signal", { exact: true }).selectOption("spi");
  await expect(channel.getByLabel("Channel pixel count", { exact: true })).toBeVisible();
  await channel.getByLabel("Virtual channel output signal", { exact: true }).selectOption("");
  await channel.getByLabel("Virtual channel protocol", { exact: true }).selectOption("ethernet");
  await expect(channel.getByLabel("Channel start universe", { exact: true })).toHaveCount(0);
  await expect(channel.getByLabel("Channel pixel count", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await page.reload();
  await page.locator('.react-flow__node[data-id="device"]').dblclick();
  await expect(channel.getByLabel("Virtual channel protocol", { exact: true })).toHaveValue("ethernet");
  await expect(channel.getByLabel("Protocol parameter value", { exact: true })).toHaveValue("20");
});
